-- SEMPRE QUE UM HÓSPEDE SAIR DO HOTEL (PREENCHER A DATA DE SAÍDA), DEVE SER
--CALCULADO O VALOR TOTAL E ALTERADO O STATUS DO APARTAMENTO;

CREATE OR REPLACE FUNCTION FUNCAO_CHECKOUT() RETURNS TRIGGER AS $$
BEGIN
IF (OLD.DT_SAIDA IS NULL AND NEW.DT_SAIDA IS NOT NULL) THEN
	UPDATE HOSPEDAGEM SET VALOR_TOTAL = (DT_SAIDA - DT_ENT) * (SELECT VALOR_DIA FROM CATEGORIA WHERE
	COD_CAT IN(SELECT COD_CAT FROM APTO WHERE NUM IN
	(SELECT NUM_QUARTO FROM HOSPEDAGEM WHERE COD_HOSPEDAGEM = OLD.COD_HOSPEDAGEM)))
	WHERE COD_HOSPEDAGEM = OLD.COD_HOSPEDAGEM;
	UPDATE APTO SET STATUS = 'D' WHERE NUM = OLD.NUM_QUARTO;
END IF;
RETURN NEW;
END;
$$ LANGUAGE PLPGSQL;

