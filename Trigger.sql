-- NÃO PERMITA QUE UM MESMO HÓSPEDE POSSUA MAIS DE UMA HOSPEDAGEM ATIVA AO MESMO TEMPO.
CREATE FUNCTION PROIBE_HOSPEDAGEM() RETURNS TRIGGER AS $$
BEGIN
IF NEW.COD_HOSP IN (SELECT COD_HOSP FROM HOSPEDAGEM WHERE DT_SAIDA IS NULL) THEN
	RAISE EXCEPTION 'Esse hóspede já possui uma hospedagem ativa.';
END IF;
RETURN NEW;
END;
$$ LANGUAGE PLPGSQL;

CREATE TRIGGER CHECA_HOSPEDE BEFORE INSERT ON HOSPEDAGEM
FOR EACH ROW EXECUTE PROCEDURE PROIBE_HOSPEDAGEM();

INSERT INTO HOSPEDAGEM(DT_ENT, COD_HOSP, NUM_QUARTO, COD_FUNC) 
