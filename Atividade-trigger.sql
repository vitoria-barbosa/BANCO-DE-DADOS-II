-- Crie a tabela Empregado2 com os atributos código (serial e chave primária), nome (varchar) e salário (integer). Crie
-- também a tabela Empregado2_audit com os seguintes atributos: usuário (varchar), data (timestamp), id (integer),
-- coluna (text), valor_antigo (text), valor_novo(text). Agora crie um trigger que não permita a alteração da chave primária e
-- insira registros na tabela Empregado2_audit para refletir as alterações realizadas na tabela Empregado2.

CREATE TABLE EMPREGADO2 (
	CODIGO SERIAL PRIMARY KEY,
	NOME VARCHAR(20),
	SALARIO INT
);

CREATE TABLE EMPREGADO2_AUDIT (
	USUARIO VARCHAR(20), 
	DT_ATUALIZACAO TIMESTAMP,
	CODIGO INT,
	COLUNA VARCHAR(20),
	VALOR_ANTIGO VARCHAR(20),
	VALOR_NOVO VARCHAR(20)
);

CREATE FUNCTION FUNCAO_AUDIT() RETURNS TRIGGER AS $$
BEGIN
	IF (NEW.CODIGO <> OLD.CODIGO) THEN
		RAISE EXCEPTION 'Não é permitido alterar a chave primária da tabela empregado2.';
	END IF;
	IF (NEW.NOME IS DISTINCT FROM OLD.NOME) THEN
		INSERT INTO EMPREGADO2_AUDIT VALUES (CURRENT_USER, NOW(), NEW.CODIGO, 'NOME', OLD.NOME, NEW.NOME);
	END IF;
	IF (NEW.SALARIO IS DISTINCT FROM OLD.SALARIO) THEN
		INSERT INTO EMPREGADO2_AUDIT VALUES (CURRENT_USER, NOW(), NEW.CODIGO, 'SALARIO', OLD.SALARIO, NEW.SALARIO);
	END IF;
	RETURN NEW;
END
$$ LANGUAGE PLPGSQL;

CREATE TRIGGER REGISTRA_UPDATE AFTER UPDATE ON EMPREGADO2
FOR EACH ROW EXECUTE PROCEDURE FUNCAO_AUDIT();

