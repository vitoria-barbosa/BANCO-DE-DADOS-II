	MATRICULA INT PRIMARY KEY,
	NOME VARCHAR(20) NOT NULL
);

CREATE FUNCTION FUNCAO_PROIBE() RETURNS TRIGGER AS $$
BEGIN
	IF (NEW.NOME ILIKE 'A%') THEN
		RAISE EXCEPTION 'NÃO É PERMITIDO CADASTRO DE ALUNOS QUE O NOME COMEÇA COMA LETRA A';
	END IF;
RETURN NEW;
END;
$$ LANGUAGE PLPGSQL;

