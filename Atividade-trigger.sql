);

CREATE TABLE EMPREGADO_AUDITORIA (
	CODIGO SERIAL PRIMARY KEY,
	OPERACAO CHAR(1) NOT NULL,
	USUARIO VARCHAR(15) NOT NULL,
	DATA_OP TIMESTAMP NOT NULL,
	NOME VARCHAR(20) NOT NULL,
	SALARIO FLOAT NOT NULL
)

CREATE OR REPLACE FUNCTION FUNCAO_REGISTRA() RETURNS TRIGGER AS $$
BEGIN
	IF (TG_OP = 'INSERT' OR TG_OP = 'UPDATE') THEN
		INSERT INTO EMPREGADO_AUDITORIA VALUES (DEFAULT, SUBSTR(TG_OP, 1, 1), CURRENT_USER, NOW(), NEW.NOME, NEW.SALARIO);
		RETURN NEW;
	END IF;
	IF (TG_OP = 'DELETE') THEN
		INSERT INTO EMPREGADO_AUDITORIA VALUES (DEFAULT, 'D', CURRENT_USER, NOW(), OLD.NOME, OLD.SALARIO);
		RETURN OLD;
	END IF;
END;
$$ LANGUAGE PLPGSQL;

